// Copies the portal's own texts (portal/portal.js → T, portal/pages.js → S, SV, ORDER, TILE)
// into functions/_lib/i18n.gen.js, so the server can pre-render /uz/ and /en/ pages for search engines
// with exactly the same words the browser shows. Run: node scripts/build-seo-i18n.mjs
// (the "Sync SEO texts" workflow runs it automatically when portal.js or pages.js change).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = fileURLToPath(new URL('..', import.meta.url));
const portal = readFileSync(root + 'portal/portal.js', 'utf8');
const pages = readFileSync(root + 'portal/pages.js', 'utf8');

// returns the source of the literal that starts right after `const NAME =`
function literal(src, name) {
  const m = src.match(new RegExp(`const ${name} = ([\\[{])`));
  if (!m) throw new Error(`const ${name} not found`);
  let i = m.index + m[0].length - 1;
  const start = i; const stack = [];
  const close = { '{': '}', '[': ']', '(': ')' };
  for (; i < src.length; i++) {
    const c = src[i];
    if (c === '/' && src[i + 1] === '/') { i = src.indexOf('\n', i); continue; }
    if (c === '/' && src[i + 1] === '*') { i = src.indexOf('*/', i) + 1; continue; }
    if (c === '"' || c === "'") { i++; while (src[i] !== c) { if (src[i] === '\\') i++; i++; } continue; }
    if (c === '`') { i++; let depth = 0; while (!(src[i] === '`' && depth === 0)) { if (src[i] === '\\') i++; else if (src[i] === '$' && src[i + 1] === '{') { depth++; i++; } else if (src[i] === '}' && depth) depth--; i++; } continue; }
    if (close[c]) stack.push(close[c]);
    else if (c === '}' || c === ']' || c === ')') { stack.pop(); if (!stack.length) return src.slice(start, i + 1); }
  }
  throw new Error(`unterminated ${name}`);
}

const ctx = { tr3: (ru, uz, en) => ({ ru, uz, en }) };
const ev = code => vm.runInNewContext('(' + code + ')', ctx);
const T = ev(literal(portal, 'T'));
const S = ev(literal(pages, 'S'));
const SV = ev(literal(pages, 'SV'));
const ORDER = ev(literal(pages, 'ORDER'));
const TILE = ev(literal(pages, 'TILE'));

// only plain strings (and lists of strings) are needed on the server
const strings = o => Object.fromEntries(Object.entries(o).filter(([, v]) => typeof v === 'string' || (Array.isArray(v) && v.every(x => typeof x === 'string'))));
const out = {
  T: Object.fromEntries(Object.entries(T).map(([l, d]) => [l, strings(d)])),
  S: Object.fromEntries(Object.entries(S).map(([l, d]) => [l, strings(d)])),
  SV: Object.fromEntries(Object.entries(SV).map(([k, v]) => [k, { art: v.art, ic: v.ic, g: v.g, app: v.app || null, p: v.p || null, t: v.t, sub: v.sub, lead: v.lead }])),
  ORDER, TILE,
};
const file = '// Generated by scripts/build-seo-i18n.mjs from portal/portal.js and portal/pages.js. Do not edit by hand.\n'
  + Object.entries(out).map(([k, v]) => `export const ${k} = ${JSON.stringify(v)};`).join('\n') + '\n';
writeFileSync(root + 'functions/_lib/i18n.gen.js', file);
console.log('functions/_lib/i18n.gen.js', file.length, 'bytes;', ORDER.length, 'services;', Object.keys(T).join('/'));

// sitemap.xml: every page in every language with its alternates, plus the app
const SITE = 'https://myuzcity.uz', LANGS = ['ru', 'uz', 'en'];
const loc = (l, k) => SITE + (l === 'ru' ? '/' : `/${l}/`) + (k || '');
const day = new Date().toISOString().slice(0, 10);
const urls = [];
for (const k of ['', ...ORDER]) for (const l of LANGS) urls.push(`<url><loc>${loc(l, k)}</loc>`
  + LANGS.map(x => `<xhtml:link rel="alternate" hreflang="${x}" href="${loc(x, k)}"/>`).join('')
  + `<xhtml:link rel="alternate" hreflang="x-default" href="${loc('ru', k)}"/><lastmod>${day}</lastmod><changefreq>${k ? 'weekly' : 'daily'}</changefreq><priority>${k ? '0.8' : '1.0'}</priority></url>`);
urls.push(`<url><loc>https://app.myuzcity.uz/</loc><lastmod>${day}</lastmod><changefreq>weekly</changefreq><priority>0.9</priority></url>`);
writeFileSync(root + 'sitemap.xml', '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n' + urls.join('\n') + '\n</urlset>\n');
console.log('sitemap.xml', urls.length, 'urls');
